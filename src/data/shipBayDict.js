/**
 * 베이사전에서 선박 데이터 조회
 * @param {string} imo - IMO 번호 (우선)
 * @param {string} code - CASP 코드 (fallback)
 * @returns {object|null} 선박 베이 데이터 또는 null
 */
export function lookupBayDict(imo, code) {
  if (imo && SHIP_BAY_DICT[imo]) return SHIP_BAY_DICT[imo];
  if (code && SHIP_BAY_DICT[code]) return SHIP_BAY_DICT[code];
  // 코드로 검색 (key가 IMO인 경우)
  if (code) {
    for (const k of Object.keys(SHIP_BAY_DICT)) {
      if (SHIP_BAY_DICT[k].code === code) return SHIP_BAY_DICT[k];
    }
  }
  return null;
}

